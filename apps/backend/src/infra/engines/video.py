import asyncio
import re
import shutil
from collections.abc import Awaitable, Callable, Coroutine
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

from loguru import logger

from infra.engines.sandbox import local_sandbox
from infra.exceptions import AnimationGenerationError
from infra.media.processor import generate_thumbnail, get_video_metadata


@dataclass
class VideoResult:
    """Represents the outcome of a successful production video render.

    Attributes:
        video_url: Accessible URL (or local path) for the rendered video.
        thumbnail_url: Optional URL for the extracted video thumbnail.
        metadata: Technical details (resolution, duration, etc.) about the video.
    """

    video_url: str
    thumbnail_url: str | None = None
    metadata: dict[str, Any] | None = None


@dataclass
class PreviewResult:
    """Represents the diagnostic outcome of a low-quality preview render.

    Attributes:
        success: Whether the render produced a valid video file.
        logs: Diagnostic output (stdout/stderr) from the render process.
        frame_path: Optional path to a specific exported frame.
        error: Descriptive error message if the render failed.
    """

    success: bool
    logs: str
    frame_path: Path | None
    error: str | None


SCENE_NAME = "SceneGen"
CODE_FILENAME = "scene.py"


def _prepare_render_environment(code: str, job_id: str) -> tuple[Path, Path | None]:
    """Prepares and validates the filesystem for a rendering job.

    Performs security sanitization on the provided Manim code and creates
    a dedicated job directory.

    Args:
        code: Raw Python code generated by an AI agent.
        job_id: Unique identifier for the generation job.

    Returns:
        A tuple of (job_directory, optional_host_mount_path).

    Raises:
        AnimationGenerationError: If the code is unsafe or directory
            creation fails.
    """
    from infra.security.sanitizer import sanitize_manim_code
    from infra.settings import get_settings

    settings = get_settings()

    # Create job directory
    job_dir = settings.jobs_dir / job_id
    job_dir.mkdir(parents=True, exist_ok=True)

    # Sanitize and write code
    sanitized_code = sanitize_manim_code(code)
    code_file = job_dir / CODE_FILENAME
    code_file.write_text(sanitized_code, encoding="utf-8")

    # Host path is relevant only if we are using Podman
    host_job_dir = settings.jobs_dir / job_id if local_sandbox.use_podman else None

    return job_dir, host_job_dir


async def render_storyboard(
    code: str,
    job_id: str,
    update_job: Callable[[dict[str, Any]], Awaitable[Any]] | None = None,
    resolution: str = "720p",
    frame_rate: int = 30,  # noqa: ARG001
) -> VideoResult:
    """Orchestrates production-quality rendering of a Manim storyboard.

    Handles the full lifecycle: environment preparation, sandboxed execution,
    progress tracking via callbacks, and post-processing of artifacts.

    Args:
        code: Sanitized Manim Python code.
        job_id: Unique identifier for the job.
        update_job: Optional async callback for progress reporting.
        resolution: Target resolution ('720p' or '1080p').
        frame_rate: Desired frames per second.

    Returns:
        A VideoResult containing artifact URLs and metadata.

    Raises:
        AnimationGenerationError: If rendering fails after retries.
    """
    job_dir, host_job_dir = _prepare_render_environment(code, job_id)

    # 3. Execute in Sandbox
    logger.info(f"Starting render for job {job_id}")

    # Retry logic for transient rendering issues
    max_retries = 2
    last_error = None

    for attempt in range(max_retries + 1):
        try:
            quality_flag = "-qh" if resolution == "1080p" else "-qm"

            def progress_callback(log_line: str) -> None:
                if update_job and ("%" in log_line or "|" in log_line):
                    match = re.search(r"(\d+)%", log_line)
                    if match:
                        progress = int(match.group(1))
                        try:
                            loop = asyncio.get_event_loop()
                            if loop.is_running():
                                coro = cast(
                                    Coroutine[Any, Any, Any],
                                    update_job({"render_progress": progress}),
                                )
                                loop.create_task(coro)
                        except Exception as e:
                            logger.debug(f"Progress update failed: {e}")

            result = await local_sandbox.run_rendering(
                job_dir=job_dir,
                code_file=CODE_FILENAME,
                scene_name=SCENE_NAME,
                host_job_dir=host_job_dir,
                quality_flag=quality_flag,
                log_callback=progress_callback,
            )

            if not result:
                raise AnimationGenerationError("Rendering sandbox unavailable")

            video_files = list(job_dir.glob("**/*.mp4"))
            if not video_files:
                logger.error(
                    f"Manim finished but no video found. Logs:\n{result.stderr}"
                )
                raise AnimationGenerationError("Manim produced no video file.")

            video_path = video_files[0]
            final_video_path = job_dir / "video.mp4"
            shutil.move(str(video_path), str(final_video_path))

            thumbnail_url = generate_thumbnail(final_video_path, job_id)
            metadata = get_video_metadata(final_video_path)

            return VideoResult(
                video_url=f"/jobs/artifacts/{job_id}/video.mp4",
                thumbnail_url=thumbnail_url,
                metadata=metadata,
            )

        except RuntimeError as e:
            logger.warning(f"Render attempt {attempt + 1} failed: {e}")
            last_error = e
            if attempt < max_retries:
                continue

    raise AnimationGenerationError(
        f"Rendering failed after retries. Last error: {last_error}"
    )


